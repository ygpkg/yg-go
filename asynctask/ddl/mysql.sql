-- asynctask schema / MySQL 8.0.1+（InnoDB、utf8mb4）；幂等，可重放；本包不执行 DDL。
-- 方言差异：无 CREATE INDEX IF NOT EXISTS（索引内联）；无部分唯一索引（用生成列模拟）。
CREATE TABLE IF NOT EXISTS core_async_task (
  id            varchar(36)  NOT NULL,
  created_at    datetime(3)  NULL,
  updated_at    datetime(3)  NULL,
  task_type     varchar(128) NOT NULL,
  status        varchar(16)  NOT NULL DEFAULT 'pending',
  priority      int          NOT NULL DEFAULT 0,
  payload       text         NULL,
  uniq_key      varchar(128) NULL,
  uniq_key_active varchar(128)
    GENERATED ALWAYS AS (IF(status IN ('pending','running'), uniq_key, NULL)) STORED,
  biz_type      varchar(64)  NOT NULL DEFAULT '',
  biz_id        varchar(64)  NOT NULL DEFAULT '',
  company_id    bigint       NOT NULL DEFAULT 0,
  subject_kind  varchar(64)  NOT NULL DEFAULT '',
  subject_id    varchar(64)  NOT NULL DEFAULT '',
  chain_id      varchar(36)  NOT NULL DEFAULT '',
  step          int          NOT NULL DEFAULT 0,
  prev_step     int          NOT NULL DEFAULT -1,
  generation    int          NOT NULL DEFAULT 1,
  attempt       int          NOT NULL DEFAULT 0,
  failure_count int          NOT NULL DEFAULT 0,
  max_attempts  int          NOT NULL DEFAULT 3,
  timeout_ms    bigint       NOT NULL DEFAULT 0,
  next_run_at   datetime(3)  NOT NULL,
  lease_until   datetime(3)  NULL,
  worker_id     varchar(64)  NOT NULL DEFAULT '',
  started_at    datetime(3)  NULL,
  finished_at   datetime(3)  NULL,
  duration_ms   bigint       NOT NULL DEFAULT 0,
  last_error    text         NULL,
  result        text         NULL,
  request_id    varchar(64)  NOT NULL DEFAULT '',
  trace_id      varchar(64)  NOT NULL DEFAULT '',
  labels        text         NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_core_async_task_uniq_active (uniq_key_active),
  KEY idx_core_async_task_claim (task_type, status, priority DESC, next_run_at),
  KEY idx_core_async_task_status_lease_until (status, lease_until),
  KEY idx_core_async_task_status_finished_at (status, finished_at),
  KEY idx_core_async_task_task_type_status_created_at (task_type, status, created_at),
  KEY idx_core_async_task_biz_type_biz_id (biz_type, biz_id),
  KEY idx_core_async_task_chain_id_step (chain_id, step),
  KEY idx_core_async_task_company_status_created (company_id, status, created_at DESC),
  KEY idx_core_async_task_subject (subject_kind, subject_id, task_type, created_at DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='asynctask 任务实体';

CREATE TABLE IF NOT EXISTS core_async_task_run (
  id             varchar(36) NOT NULL,
  created_at     datetime(3) NULL,
  async_task_id  varchar(36) NOT NULL,
  generation     int         NOT NULL DEFAULT 1,
  attempt        int         NOT NULL,
  status         varchar(16) NOT NULL,
  failure_kind   varchar(16) NOT NULL DEFAULT '',
  worker_id      varchar(64) NOT NULL DEFAULT '',
  started_at     datetime(3) NOT NULL,
  finished_at    datetime(3) NULL,
  duration_ms    bigint      NOT NULL DEFAULT 0,
  result         text        NULL,
  error_msg      text        NULL,
  request_id     varchar(64) NOT NULL DEFAULT '',
  trace_id       varchar(64) NOT NULL DEFAULT '',
  PRIMARY KEY (id),
  UNIQUE KEY uk_core_async_task_run_async_task_id_generation_attempt (async_task_id, generation, attempt),
  KEY idx_core_async_task_run_created_at (created_at),
  KEY idx_core_async_task_run_status_started_at (status, started_at),
  KEY idx_core_async_task_run_request_id (request_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='asynctask 单次尝试记录';

CREATE TABLE IF NOT EXISTS core_async_task_type (
  id          varchar(36)  NOT NULL,
  task_type   varchar(128) NOT NULL,
  enabled     tinyint(1)   NOT NULL DEFAULT 1,
  updated_at  datetime(3)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_core_async_task_type_task_type (task_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='asynctask 类型开关';
